#!/usr/bin/env python3
"""Generates the index table of Notes/solutions/README.md from each entry's front matter.

Usage:
  scripts/solutions-index.py             rewrite the block between the markers
  scripts/solutions-index.py --check     exit 1 when the block is stale or an entry is malformed
  scripts/solutions-index.py --self-test run the fixture tests (a temporary directory)

An entry is Notes/solutions/YYYY-MM-DD-<slug>.md. The generator reads three front matter fields:
  title: "<index text>"   one line, double-quoted; escape \\" and \\\\; no "|"
  date: YYYY-MM-DD        equal to the filename's date prefix
  tags:                   a block list of "  - <tag>" lines (may be empty)
Everything else in the front matter is ignored. Standard library only.
"""
import datetime
import difflib
import io
import pathlib
import re
import shutil
import sys
import tempfile

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOLUTIONS = ROOT / "Notes" / "solutions"
BEGIN = "<!-- solutions-index:begin (generated by scripts/solutions-index.py; do not edit) -->"
END = "<!-- solutions-index:end -->"
HEADER = ["| Date | Entry | Tags |", "|---|---|---|"]
FILENAME = re.compile(r"^(\d{4}-\d{2}-\d{2})-[A-Za-z0-9][A-Za-z0-9._-]*\.md$")
KEY_LINE = re.compile(r"^([A-Za-z_][A-Za-z0-9_]*):(.*)$")
QUOTED_TITLE = re.compile(r'^"((?:[^"\\]|\\["\\])*)"$')
TAG_LINE = re.compile(r"^  - (\S.*)$")
FIX_HINT = "run scripts/solutions-index.py"


class Entry:
    def __init__(self, name, date, title, tags):
        self.name, self.date, self.title, self.tags = name, date, title, tags

    def row(self):
        return f"| {self.date} | [{self.title}]({self.name}) | {', '.join(self.tags)} |"


def read_exact(path):
    """The file's text with its line endings untouched."""
    with open(path, encoding="utf-8", newline="") as handle:
        return handle.read()


def front_matter_lines(text):
    lines = text.split("\n")
    if lines[0] != "---" or "---" not in lines[1:]:
        return None
    return lines[1:lines.index("---", 1)]


def fields(block):
    """The title, date and tags fields of a front matter block: key -> (value, indented lines)."""
    found = {}
    key = None
    for line in block:
        if not line.startswith(" "):
            match = KEY_LINE.match(line)
            key = match.group(1) if match else None
            if key in ("title", "date", "tags"):
                found[key] = (match.group(2).strip(), [])
        elif key in found:
            found[key][1].append(line)
    return found


def parse_entry(path):
    """The entry in `path` and its errors (each a message; the file name is added by the caller)."""
    name = path.name
    match = FILENAME.match(name)
    if not match:
        return None, ["the name is not YYYY-MM-DD-<slug>.md"]
    block = front_matter_lines(path.read_text(encoding="utf-8"))
    if block is None:
        return None, ["no front matter (the file must start with a --- line and have a closing ---)"]
    found = fields(block)
    errors = []

    title = None
    if "title" not in found:
        errors.append("missing title")
    else:
        quoted = QUOTED_TITLE.match(found["title"][0])
        if not quoted:
            errors.append('title must be one double-quoted line (escape " and \\ the YAML way)')
        else:
            title = re.sub(r'\\(["\\])', r"\1", quoted.group(1))
            if not title.strip():
                errors.append("empty title")
                title = None
            elif "|" in title:
                errors.append("title contains |")

    date = None
    if "date" not in found:
        errors.append("missing date")
    else:
        raw = found["date"][0]
        quoted = re.match(r"""^(["'])(.*)\1$""", raw)
        raw = quoted.group(2) if quoted else raw
        try:
            if not re.match(r"^\d{4}-\d{2}-\d{2}$", raw):
                raise ValueError(raw)
            datetime.date.fromisoformat(raw)
            date = raw
        except ValueError:
            errors.append(f"malformed date {raw!r} (YYYY-MM-DD)")
        if date is not None and date != match.group(1):
            errors.append(f"date {date} does not match the filename's {match.group(1)}")

    tags = []
    if "tags" in found:
        value, items = found["tags"]
        if value:
            errors.append("tags must be a block list of '  - <tag>' lines")
        for item in items:
            tag = TAG_LINE.match(item)
            text = tag.group(1).strip() if tag else None
            if text is None or text[0] in "\"'[{#" or "|" in text:
                errors.append(f"malformed tags line {item!r}")
            else:
                tags.append(text)

    if errors:
        return None, errors
    return Entry(name, date, title, tags), []


def load_entries(solutions):
    entries, errors = [], []
    for path in sorted(solutions.iterdir()):
        if path.name == "README.md" or path.is_dir():
            continue
        entry, problems = parse_entry(path)
        errors += [f"{path.name}: {problem}" for problem in problems]
        if entry:
            entries.append(entry)
    entries.sort(key=lambda entry: (entry.date, entry.name))
    return entries, errors


def block_lines(entries):
    return [BEGIN, "", *HEADER, *[entry.row() for entry in entries], "", END]


def replace_block(readme, entries):
    """The README text with its block regenerated, or None and a message when the markers are wrong."""
    lines = readme.split("\n")
    begins = [i for i, line in enumerate(lines) if line == BEGIN]
    ends = [i for i, line in enumerate(lines) if line == END]
    if len(begins) != 1 or len(ends) != 1:
        return None, f"README.md: needs exactly one begin and one end marker line, found {len(begins)} and {len(ends)}"
    if begins[0] > ends[0]:
        return None, "README.md: the end marker comes before the begin marker"
    return "\n".join(lines[: begins[0]] + block_lines(entries) + lines[ends[0] + 1 :]), None


def run(argv, solutions=SOLUTIONS, out=sys.stdout):
    if argv not in ([], ["--check"]):
        print("usage: scripts/solutions-index.py [--check | --self-test]", file=out)
        return 2
    readme_path = solutions / "README.md"
    entries, errors = load_entries(solutions)
    old = read_exact(readme_path)
    new, marker_error = replace_block(old, entries)
    if marker_error:
        errors.append(marker_error)
    if errors:
        for error in errors:
            print(error, file=out)
        return 1
    if new == old:
        return 0
    if argv == ["--check"]:
        diff = difflib.unified_diff(
            old.split("\n"), new.split("\n"), "Notes/solutions/README.md", "generated", lineterm=""
        )
        print("\n".join(diff), file=out)
        print(FIX_HINT, file=out)
        return 1
    readme_path.write_text(new, encoding="utf-8", newline="")
    return 0


# --- self-test ---

PRE = "# Solutions\n\nintro  \twith trailing blanks, é, no tricks\n\n## Index\n\n"
POST = "\n## After the index\n  indented, with trailing blanks  \nlast line without a newline"


def entry_text(title, date, tags, module="M"):
    tag_lines = "".join(f"  - {tag}\n" for tag in tags)
    return f'---\ntitle: "{title}"\nmodule: {module}\ndate: {date}\ntags:\n{tag_lines}---\n\n# Body\n'


TEMP_DIRECTORIES = []


def fixture(entries, readme=None):
    directory = pathlib.Path(tempfile.mkdtemp(prefix="solutions-index-test-"))
    TEMP_DIRECTORIES.append(directory)
    for name, text in entries.items():
        (directory / name).write_text(text, encoding="utf-8")
    (directory / "README.md").write_text(
        readme if readme is not None else PRE + BEGIN + "\n" + END + POST, encoding="utf-8", newline=""
    )
    return directory


def call(argv, directory):
    out = io.StringIO()
    code = run(argv, directory, out)
    return code, out.getvalue()


def read(directory):
    return read_exact(directory / "README.md")


GOOD = {
    "2026-11-05-b-second.md": entry_text("Alpha", "2026-11-05", ["x", "y z"]),
    "2026-11-05-a-first.md": entry_text("Zebra", "2026-11-05", ["one"]),
    "2026-11-04-z-earlier.md": entry_text("Mid", "2026-11-04", []),
}
EXPECTED_ROWS = [
    "| 2026-11-04 | [Mid](2026-11-04-z-earlier.md) |  |",
    "| 2026-11-05 | [Zebra](2026-11-05-a-first.md) | one |",
    "| 2026-11-05 | [Alpha](2026-11-05-b-second.md) | x, y z |",
]


def self_test():
    failures = []

    def expect(condition, message):
        print(("ok   " if condition else "FAIL ") + message)
        if not condition:
            failures.append(message)

    expected = PRE + "\n".join([BEGIN, "", *HEADER, *EXPECTED_ROWS, "", END]) + POST

    # 1. Generate: date, then filename; tags joined with ", ".
    directory = fixture(GOOD)
    code, _ = call([], directory)
    expect(code == 0 and read(directory) == expected, "1 generate: rows in date-then-filename order, tags joined")

    # 2. Idempotent.
    code, _ = call([], directory)
    expect(code == 0 and read(directory) == expected, "2 idempotent: a second run changes no byte")
    expect(call(["--check"], directory)[0] == 0, "2 --check passes on a generated README")

    # 3. Stale: a row edited by hand.
    stale = directory / "README.md"
    stale.write_text(expected.replace("[Zebra]", "[Zebra!]"), encoding="utf-8", newline="")
    code, output = call(["--check"], directory)
    expect(code == 1 and "[Zebra!]" in output and FIX_HINT in output, "3 stale row: --check exits 1 and names the row")

    # 4. Missing row: an entry added without regenerating.
    directory = fixture(GOOD)
    call([], directory)
    (directory / "2026-11-06-new.md").write_text(entry_text("New", "2026-11-06", ["n"]), encoding="utf-8")
    code, output = call(["--check"], directory)
    expect(code == 1 and "2026-11-06-new.md" in output, "4 missing row: --check exits 1")

    # 5. A union-merge leftover: a duplicated row.
    directory = fixture(GOOD)
    call([], directory)
    duplicated = EXPECTED_ROWS[1]
    (directory / "README.md").write_text(
        read(directory).replace(duplicated, duplicated + "\n" + duplicated), encoding="utf-8", newline=""
    )
    expect(call(["--check"], directory)[0] == 1, "5 duplicated row: --check exits 1")
    call([], directory)
    expect(read(directory) == expected and call(["--check"], directory)[0] == 0, "5 regenerating fixes it")

    # 6. Entry errors, one fixture each: --check and the generator fail, naming the file.
    bad = {
        "no front matter": ("2026-11-07-bad.md", "# No front matter\n"),
        "unclosed front matter": ("2026-11-07-bad.md", '---\ntitle: "T"\ndate: 2026-11-07\n'),
        "no title": ("2026-11-07-bad.md", "---\ndate: 2026-11-07\ntags:\n---\n"),
        "no date": ("2026-11-07-bad.md", '---\ntitle: "T"\ntags:\n---\n'),
        "date differs from the filename": ("2026-11-07-bad.md", entry_text("T", "2026-11-08", [])),
        "malformed date": ("2026-11-07-bad.md", entry_text("T", "2026-13-45", [])),
        "| in a title": ("2026-11-07-bad.md", entry_text("a | b", "2026-11-07", [])),
        "unquoted title": ("2026-11-07-bad.md", "---\ntitle: T\ndate: 2026-11-07\ntags:\n---\n"),
        "inline tags": ("2026-11-07-bad.md", '---\ntitle: "T"\ndate: 2026-11-07\ntags: [a, b]\n---\n'),
        "a bad filename": ("notes.md", entry_text("T", "2026-11-07", [])),
    }
    for label, (name, text) in bad.items():
        directory = fixture(GOOD)
        call([], directory)
        before = read(directory)
        (directory / name).write_text(text, encoding="utf-8")
        code, output = call(["--check"], directory)
        generated, _ = call([], directory)
        expect(
            code == 1 and output.splitlines()[0].startswith(f"{name}: ") and generated == 1 and read(directory) == before,
            f"6 {label}: both modes exit 1 with '{name}: <message>', nothing written",
        )

    # 7. Outside the markers: byte for byte.
    directory = fixture(GOOD)
    call([], directory)
    text = read(directory)
    expect(
        text.startswith(PRE + BEGIN + "\n") and text.endswith(END + POST),
        "7 text before and after the block is preserved byte for byte",
    )

    # 8. Markers missing or doubled: an error, nothing written.
    for label, readme in {
        "no markers": PRE + POST,
        "no end marker": PRE + BEGIN + POST,
        "a doubled begin marker": PRE + BEGIN + "\n" + BEGIN + "\n" + END + POST,
        "a doubled end marker": PRE + BEGIN + "\n" + END + "\n" + END + POST,
        "the end before the begin": PRE + END + "\n" + BEGIN + POST,
    }.items():
        directory = fixture(GOOD, readme)
        code, output = call([], directory)
        check_code, _ = call(["--check"], directory)
        expect(
            code == 1 and check_code == 1 and output.startswith("README.md: ") and read(directory) == readme,
            f"8 {label}: an error, nothing written",
        )

    # 9. A title with a quote and a backslash round-trips.
    directory = fixture({"2026-11-08-q.md": entry_text('A \\"quoted\\" and \\\\ b', "2026-11-08", [])})
    call([], directory)
    expect(
        '| 2026-11-08 | [A "quoted" and \\ b](2026-11-08-q.md) |  |' in read(directory),
        "9 a title's \\\" and \\\\ escapes are read",
    )

    for directory in TEMP_DIRECTORIES:
        shutil.rmtree(directory, ignore_errors=True)
    if failures:
        print(f"solutions-index self-test: {len(failures)} failed")
        return 1
    print("solutions-index self-test: all passed")
    return 0


def main(argv):
    if argv == ["--self-test"]:
        return self_test()
    return run(argv)


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
