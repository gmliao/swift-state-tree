#!/usr/bin/env bash
# Builds each snippet in scripts/must-not-compile/ as its own target of a throwaway SwiftPM
# package that depends on this repository by path, and checks the outcome its first line names:
#   // expect: compiles               the snippet must build (a control for the setup)
#   // expect-error: <text>           the build must fail with an error line containing <text>
#                                     (not the source excerpt the compiler echoes beside it)
# Prelude.swift is compiled into every snippet's target. SwiftPM resolves the dependencies'
# module maps itself, on macOS and Linux alike. The package and its build live under
# .build/must-not-compile/ (the first run builds the library there; later runs are incremental).
# Usage, from anywhere: scripts/check-must-not-compile.sh
set -euo pipefail

root="$(cd "$(dirname "$0")/.." && pwd)"
snippets_dir="$root/scripts/must-not-compile"
prelude="$snippets_dir/Prelude.swift"
work="$root/.build/must-not-compile"
package="$work/package"
scratch="$work/build"
# A path dependency's identity is its directory's name, lowercased.
identity="$(basename "$root" | tr '[:upper:]' '[:lower:]')"

snippets=()
for snippet in "$snippets_dir"/*.swift; do
    [[ "$snippet" == "$prelude" ]] && continue
    snippets+=("$snippet")
done

# One target per snippet, named after its file.
target_name() {
    local base
    base="$(basename "$1" .swift)"
    echo "Snippet_${base//-/_}"
}

rm -rf "$package"
mkdir -p "$package/Sources"
{
    echo '// swift-tools-version: 6.0'
    echo '// Generated by scripts/check-must-not-compile.sh; not part of the repository.'
    echo 'import PackageDescription'
    echo 'let package = Package('
    echo '    name: "MustNotCompile",'
    echo '    platforms: [.macOS(.v14)],'
    echo "    dependencies: [.package(path: \"$root\")],"
    echo '    targets: ['
    for snippet in "${snippets[@]}"; do
        name="$(target_name "$snippet")"
        echo "        .target(name: \"$name\", dependencies: [.product(name: \"SwiftStateTree\", package: \"$identity\")]),"
    done
    echo '    ],'
    echo '    swiftLanguageModes: [.v5]'
    echo ')'
} > "$package/Package.swift"
# The repository's pins, so the dependencies resolve to the versions it builds with.
cp "$root/Package.resolved" "$package/Package.resolved"
for snippet in "${snippets[@]}"; do
    name="$(target_name "$snippet")"
    mkdir -p "$package/Sources/$name"
    cp "$prelude" "$package/Sources/$name/Prelude.swift"
    cp "$snippet" "$package/Sources/$name/$(basename "$snippet")"
done

failures=0
for snippet in "${snippets[@]}"; do
    name="$(basename "$snippet")"
    header="$(head -n 1 "$snippet")"
    set +e
    output="$(swift build --package-path "$package" --scratch-path "$scratch" --target "$(target_name "$snippet")" 2>&1)"
    status=$?
    set -e
    errors="$(grep -F -- "error:" <<<"$output" || true)"
    case "$header" in
        "// expect: compiles")
            if [[ $status -ne 0 ]]; then
                echo "FAIL $name: expected to compile, got:"
                echo "${errors:-$output}" | sed -n 1,5p
                failures=$((failures + 1))
            else
                echo "ok   $name compiles"
            fi
            ;;
        "// expect-error: "*)
            expected="${header#// expect-error: }"
            if [[ $status -eq 0 ]]; then
                echo "FAIL $name: compiled, expected an error containing: $expected"
                failures=$((failures + 1))
            elif ! grep -F -q -- "$expected" <<<"$errors"; then
                echo "FAIL $name: failed without the expected error ($expected); got:"
                echo "${errors:-$output}" | sed -n 1,5p
                failures=$((failures + 1))
            # The error must come from the snippet, not from the library or the setup.
            elif [[ "$(grep -F -- "$expected" <<<"$errors")" != *"/$name:"* ]]; then
                echo "FAIL $name: the expected error is not in the snippet; got:"
                echo "$errors" | sed -n 1,5p
                failures=$((failures + 1))
            else
                echo "ok   $name refused: $expected"
            fi
            ;;
        *)
            echo "FAIL $name: its first line names no expectation"
            failures=$((failures + 1))
            ;;
    esac
done

if [[ $failures -ne 0 ]]; then
    echo "check-must-not-compile: $failures of ${#snippets[@]} snippets failed"
    exit 1
fi
echo "check-must-not-compile: ${#snippets[@]} snippets as expected"
